-- 1. Enable Archive Log & Supplemental Logging for CDC
SHUTDOWN IMMEDIATE;
STARTUP MOUNT;
ALTER DATABASE ARCHIVELOG;
ALTER DATABASE OPEN;
ALTER DATABASE ADD SUPPLEMENTAL LOG DATA;

-- 2. Create Debezium CDC User with Required Privileges
BEGIN
  EXECUTE IMMEDIATE 'CREATE USER c##dbzuser IDENTIFIED BY dbz_password CONTAINER=ALL';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

GRANT CREATE SESSION TO c##dbzuser CONTAINER=ALL;
GRANT SET CONTAINER TO c##dbzuser CONTAINER=ALL;
GRANT SELECT ON V_$DATABASE TO c##dbzuser CONTAINER=ALL;
GRANT SELECT ON V_$INSTANCE TO c##dbzuser CONTAINER=ALL;
GRANT SELECT ON V_$VERSION TO c##dbzuser CONTAINER=ALL;
GRANT SELECT ANY DICTIONARY TO c##dbzuser CONTAINER=ALL;
GRANT FLASHBACK ANY TABLE TO c##dbzuser CONTAINER=ALL;
GRANT SELECT ANY TABLE TO c##dbzuser CONTAINER=ALL;
GRANT SELECT_CATALOG_ROLE TO c##dbzuser CONTAINER=ALL;
GRANT EXECUTE_CATALOG_ROLE TO c##dbzuser CONTAINER=ALL;
GRANT SELECT ANY TRANSACTION TO c##dbzuser CONTAINER=ALL;
GRANT LOGMINING TO c##dbzuser CONTAINER=ALL;
GRANT CREATE TABLE TO c##dbzuser CONTAINER=ALL;
ALTER USER c##dbzuser QUOTA UNLIMITED ON USERS CONTAINER=ALL;
ALTER USER c##dbzuser SET CONTAINER_DATA = ALL CONTAINER=CURRENT;


-- 3. Drop local view if present
BEGIN
  EXECUTE IMMEDIATE 'DROP VIEW c##dbzuser.v$version';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

-- 4. Compatibility view & public synonym for Debezium 2.4 parser on Oracle 23ai
CREATE OR REPLACE VIEW SYS.DEBEZIUM_VERSION AS
SELECT 
  'Oracle Database 23ai Free Release 23.26.3.0.0 - Production' AS BANNER,
  'Oracle Database 23ai Free Release 23.26.3.0.0 - Production' AS BANNER_FULL,
  'Oracle Database 23ai Free Release 23.26.3.0.0 - Production' AS BANNER_LEGACY,
  0 AS CON_ID
FROM DUAL;

GRANT SELECT ON SYS.DEBEZIUM_VERSION TO PUBLIC;
CREATE OR REPLACE PUBLIC SYNONYM V$VERSION FOR SYS.DEBEZIUM_VERSION;

EXIT;
