ALTER SESSION SET CONTAINER = FREEPDB1;

-- 1. Create Application User
BEGIN
  EXECUTE IMMEDIATE 'CREATE USER WALLET_APP IDENTIFIED BY "WalletApp123!" DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS';
EXCEPTION
  WHEN OTHERS THEN NULL;
END;
/

GRANT CREATE SESSION, CREATE TABLE TO WALLET_APP;

-- 2. Create Tables
BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE WALLET_APP.TRANSACTIONS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE WALLET_APP.WALLETS CASCADE CONSTRAINTS';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE WALLET_APP.WALLETS (
  WALLET_ID NUMBER PRIMARY KEY,
  USER_ID NUMBER NOT NULL,
  BALANCE NUMBER(18,2) DEFAULT 0.00,
  CURRENCY VARCHAR2(10) DEFAULT 'THB',
  STATUS VARCHAR2(20) DEFAULT 'ACTIVE',
  UPDATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE WALLET_APP.TRANSACTIONS (
  TX_ID NUMBER PRIMARY KEY,
  WALLET_ID NUMBER NOT NULL,
  AMOUNT NUMBER(18,2) NOT NULL,
  TX_TYPE VARCHAR2(20) NOT NULL,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT FK_TX_WALLET FOREIGN KEY (WALLET_ID) REFERENCES WALLET_APP.WALLETS(WALLET_ID)
);

-- 3. Supplemental Logging for CDC
ALTER TABLE WALLET_APP.WALLETS ADD SUPPLEMENTAL LOG DATA (ALL) COLUMNS;
ALTER TABLE WALLET_APP.TRANSACTIONS ADD SUPPLEMENTAL LOG DATA (ALL) COLUMNS;

-- 4. Grants to Debezium CDC User
GRANT SELECT ON WALLET_APP.WALLETS TO c##dbzuser;
GRANT SELECT ON WALLET_APP.TRANSACTIONS TO c##dbzuser;
GRANT FLASHBACK ON WALLET_APP.WALLETS TO c##dbzuser;
GRANT FLASHBACK ON WALLET_APP.TRANSACTIONS TO c##dbzuser;

