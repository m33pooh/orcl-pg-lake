CREATE TABLE ECOMMERCE_APP.CUSTOMERS (
  CUSTOMER_ID NUMBER PRIMARY KEY,
  NAME VARCHAR2(100) NOT NULL,
  EMAIL VARCHAR2(150) NOT NULL,
  TIER VARCHAR2(20) DEFAULT 'STANDARD',
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE ECOMMERCE_APP.ORDERS (
  ORDER_ID NUMBER PRIMARY KEY,
  CUSTOMER_ID NUMBER NOT NULL,
  TOTAL_AMOUNT NUMBER(18,2) NOT NULL,
  STATUS VARCHAR2(20) DEFAULT 'PENDING',
  ORDER_DATE TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT FK_ORD_CUST FOREIGN KEY (CUSTOMER_ID) REFERENCES ECOMMERCE_APP.CUSTOMERS(CUSTOMER_ID)
);

