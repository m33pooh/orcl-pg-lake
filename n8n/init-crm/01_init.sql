-- Initialization script for CRM App
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE TABLE IF NOT EXISTS support_tickets (
    ticket_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id NUMBER NOT NULL,
    subject VARCHAR2(255) NOT NULL,
    status VARCHAR2(30) DEFAULT 'OPEN',
    priority VARCHAR2(20) DEFAULT 'NORMAL',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS ticket_messages (
    message_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id NUMBER NOT NULL,
    sender_type VARCHAR2(20) NOT NULL,
    message_text CLOB NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_tickets_status ON support_tickets(status, created_at);
