-- Initialization script for Wallet App
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE TABLE IF NOT EXISTS wallets (
    wallet_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    balance NUMBER(14, 2) DEFAULT 0.00 NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS wallet_transactions (
    txn_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id NUMBER NOT NULL,
    txn_type VARCHAR2(20) NOT NULL,
    amount NUMBER(14, 2) NOT NULL,
    status VARCHAR2(20) DEFAULT 'COMPLETED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_wallet_txn_date ON wallet_transactions(created_at);
